-- Spring Session 4.1.1 epoch/bytea 구조. JSON converter와 전용 SQL을 함께 사용한다.
CREATE SCHEMA IF NOT EXISTS auth_session;
CREATE TABLE auth_session."SPRING_SESSION" (
    "PRIMARY_ID" char(36)
       
       
        CONSTRAINT "NN_SPRING_SESSION_PRIMARY_ID" NOT NULL
       
       
        CONSTRAINT "PK_SPRING_SESSION" PRIMARY KEY
    , "SESSION_ID" char(36)
       
       
        CONSTRAINT "NN_SPRING_SESSION_SESSION_ID" NOT NULL
       
       
        CONSTRAINT "UX_SPRING_SESSION_SESSION_ID" UNIQUE
    , "CREATION_TIME" bigint
       
       
        CONSTRAINT "NN_SPRING_SESSION_CREATION_TIME" NOT NULL
    , "LAST_ACCESS_TIME" bigint
       
       
        CONSTRAINT "NN_SPRING_SESSION_LAST_ACCESS_TIME" NOT NULL
    , "MAX_INACTIVE_INTERVAL" integer
       
       
        CONSTRAINT "NN_SPRING_SESSION_MAX_INACTIVE_INTERVAL" NOT NULL
    , "EXPIRY_TIME" bigint
       
       
        CONSTRAINT "NN_SPRING_SESSION_EXPIRY_TIME" NOT NULL
    , "PRINCIPAL_NAME" varchar(100)
);
CREATE INDEX "IX_SPRING_SESSION_EXPIRY" ON auth_session."SPRING_SESSION" ("EXPIRY_TIME");
CREATE INDEX "IX_SPRING_SESSION_PRINCIPAL" ON auth_session."SPRING_SESSION" ("PRINCIPAL_NAME");
CREATE TABLE auth_session."SPRING_SESSION_ATTRIBUTES" (
    "SESSION_PRIMARY_ID" char(36)
       
       
        CONSTRAINT "NN_SPRING_SESSION_ATTRIBUTES_SESSION_PRIMARY_ID" NOT NULL
       
       
        CONSTRAINT "FK_SPRING_SESSION_ATTRIBUTES_SESSION_PRIMARY_ID"
        REFERENCES auth_session."SPRING_SESSION" ("PRIMARY_ID") ON DELETE CASCADE
    , "ATTRIBUTE_NAME" varchar(200)
       
       
        CONSTRAINT "NN_SPRING_SESSION_ATTRIBUTES_ATTRIBUTE_NAME" NOT NULL
    , "ATTRIBUTE_BYTES" bytea
       
       
        CONSTRAINT "NN_SPRING_SESSION_ATTRIBUTES_ATTRIBUTE_BYTES" NOT NULL
    , CONSTRAINT "PK_SPRING_SESSION_ATTRIBUTES" PRIMARY KEY ("SESSION_PRIMARY_ID", "ATTRIBUTE_NAME")
);
