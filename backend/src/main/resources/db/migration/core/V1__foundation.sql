-- 기본 업무·감사 객체. 선택 인증/세션과 local 객체는 독립 경로에서 적용한다.
CREATE TABLE "APP_USER" (
    "USER_ID" bigint
       
       
        CONSTRAINT "NN_APP_USER_USER_ID" NOT NULL
       
       
        GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME "SEQ_APP_USER_USER_ID")
       
       
        CONSTRAINT "PK_APP_USER" PRIMARY KEY
    , "LOGIN_ID" varchar(50)
       
       
        CONSTRAINT "NN_APP_USER_LOGIN_ID" NOT NULL
       
       
        CONSTRAINT "UX_APP_USER_LOGIN_ID" UNIQUE
       
       
        CONSTRAINT "CK_APP_USER_LOGIN_ID" CHECK ("LOGIN_ID" ~ '^[a-z0-9][a-z0-9._-]{2,49}$')
    , "DISPLAY_NAME" varchar(100)
       
       
        CONSTRAINT "NN_APP_USER_DISPLAY_NAME" NOT NULL
       
       
        CONSTRAINT "CK_APP_USER_DISPLAY_NAME" CHECK (length("DISPLAY_NAME") > 0)
    , "EMAIL" varchar(254)
    , "STATUS" varchar(16)
       
       
        CONSTRAINT "NN_APP_USER_STATUS" NOT NULL
       
       
        CONSTRAINT "CK_APP_USER_STATUS" CHECK ("STATUS" IN ('ACTIVE', 'INACTIVE'))
    , "CREATED_AT" timestamptz(3)
       
       
        CONSTRAINT "NN_APP_USER_CREATED_AT" NOT NULL
    , "CREATED_BY" bigint
    , "UPDATED_AT" timestamptz(3)
       
       
        CONSTRAINT "NN_APP_USER_UPDATED_AT" NOT NULL
    , "UPDATED_BY" bigint
    , "VERSION" bigint
       
       
        CONSTRAINT "NN_APP_USER_VERSION" NOT NULL DEFAULT 0
       
       
        CONSTRAINT "CK_APP_USER_VERSION" CHECK ("VERSION" >= 0)
);
