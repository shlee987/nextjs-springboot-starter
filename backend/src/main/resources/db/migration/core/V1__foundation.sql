CREATE TABLE "ACCESS_AUDIT" (
    "AUDIT_ID" uuid
       
       
        CONSTRAINT "NN_ACCESS_AUDIT_AUDIT_ID" NOT NULL
       
       
        CONSTRAINT "PK_ACCESS_AUDIT" PRIMARY KEY
    , "OCCURRED_AT" timestamptz(3)
       
       
        CONSTRAINT "NN_ACCESS_AUDIT_OCCURRED_AT" NOT NULL
    , "ACTOR_USER_ID" bigint
    , "ACTOR_KIND" varchar(16)
       
       
        CONSTRAINT "NN_ACCESS_AUDIT_ACTOR_KIND" NOT NULL
       
       
        CONSTRAINT "CK_ACCESS_AUDIT_ACTOR_KIND"
        CHECK ("ACTOR_KIND" IN ('USER', 'ANONYMOUS', 'SYSTEM'))
    , "RESOURCE_CODE" varchar(64)
       
       
        CONSTRAINT "NN_ACCESS_AUDIT_RESOURCE_CODE" NOT NULL
    , "ACTION_CODE" varchar(32)
       
       
        CONSTRAINT "NN_ACCESS_AUDIT_ACTION_CODE" NOT NULL
    , "TARGET_TYPE" varchar(64)
    , "TARGET_ID" varchar(128)
    , "OUTCOME" varchar(16)
       
       
        CONSTRAINT "NN_ACCESS_AUDIT_OUTCOME" NOT NULL
       
       
        CONSTRAINT "CK_ACCESS_AUDIT_OUTCOME"
        CHECK ("OUTCOME" IN ('STARTED', 'SUCCESS', 'FAILURE', 'DENIED', 'UNKNOWN'))
    , "REASON_CODE" varchar(64)
    , "TRACE_ID" uuid
       
       
        CONSTRAINT "NN_ACCESS_AUDIT_TRACE_ID" NOT NULL
    , "SERVER_ID" varchar(100)
       
       
        CONSTRAINT "NN_ACCESS_AUDIT_SERVER_ID" NOT NULL
    , "CLIENT_IP" inet
    , "USER_AGENT" varchar(256)
    , "OPERATION_ID" uuid
);
