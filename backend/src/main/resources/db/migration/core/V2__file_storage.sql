-- 완료 상태만 공개한다. 예약/삭제 중인 바이트도 quota에 포함한다.
CREATE TABLE "FILE_OWNER_QUOTA" (
    "OWNER_USER_ID" bigint CONSTRAINT "PK_FILE_OWNER_QUOTA" PRIMARY KEY
        CONSTRAINT "FK_FILE_OWNER_QUOTA_USER" REFERENCES "APP_USER" ("USER_ID")
    , "USED_BYTES" bigint CONSTRAINT "NN_FILE_OWNER_QUOTA_USED_BYTES" NOT NULL DEFAULT 0
    , CONSTRAINT "CK_FILE_OWNER_QUOTA_USED_BYTES" CHECK ("USED_BYTES" BETWEEN 0 AND 104857600)
);
CREATE TABLE "FILE_ASSET" (
    "FILE_ID" uuid CONSTRAINT "PK_FILE_ASSET" PRIMARY KEY
    , "OWNER_USER_ID" bigint CONSTRAINT "NN_FILE_ASSET_OWNER_USER_ID" NOT NULL
        CONSTRAINT "FK_FILE_ASSET_OWNER_USER" REFERENCES "APP_USER" ("USER_ID")
    , "STORAGE_KEY" varchar(40) CONSTRAINT "NN_FILE_ASSET_STORAGE_KEY" NOT NULL
        CONSTRAINT "UK_FILE_ASSET_STORAGE_KEY" UNIQUE
    , "ORIGINAL_NAME" varchar(240) CONSTRAINT "NN_FILE_ASSET_ORIGINAL_NAME" NOT NULL
    , "CONTENT_TYPE" varchar(16) CONSTRAINT "NN_FILE_ASSET_CONTENT_TYPE" NOT NULL
    , "SIZE_BYTES" bigint CONSTRAINT "NN_FILE_ASSET_SIZE_BYTES" NOT NULL
    , "WIDTH" integer CONSTRAINT "NN_FILE_ASSET_WIDTH" NOT NULL
    , "HEIGHT" integer CONSTRAINT "NN_FILE_ASSET_HEIGHT" NOT NULL
    , "CREATED_AT" timestamptz(3) CONSTRAINT "NN_FILE_ASSET_CREATED_AT" NOT NULL
    , "STATUS" varchar(8) CONSTRAINT "NN_FILE_ASSET_STATUS" NOT NULL
    , CONSTRAINT "CK_FILE_ASSET_CONTENT_TYPE" CHECK ("CONTENT_TYPE" IN ('image/png', 'image/jpeg'))
    , CONSTRAINT "CK_FILE_ASSET_SIZE_BYTES" CHECK ("SIZE_BYTES" BETWEEN 1 AND 5242880)
    , CONSTRAINT "CK_FILE_ASSET_DIMENSIONS" CHECK (
        "WIDTH" BETWEEN 1 AND 8192
        AND "HEIGHT" BETWEEN 1 AND 8192
        AND "WIDTH"::bigint * "HEIGHT" <= 16000000
    )
    , CONSTRAINT "CK_FILE_ASSET_STATUS" CHECK ("STATUS" IN ('PENDING', 'READY', 'DELETING'))
);
CREATE INDEX "IX_FILE_ASSET_OWNER_CREATED"
    ON "FILE_ASSET" ("OWNER_USER_ID", "CREATED_AT" DESC, "FILE_ID" DESC)
    WHERE "STATUS" = 'READY';
